def get_saturday_date(reference=None, include_today=False):
    ref = reference or now_sp()
    days_ahead = (5 - ref.weekday() + 7) % 7
    if days_ahead == 0 and not include_today:
        days_ahead = 7
    return (ref + timedelta(days=days_ahead)).date()

