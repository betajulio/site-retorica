    url = f"https://api.green-api.com/waInstance{ID_INSTANCE}/sendMessage/{API_TOKEN}"
    payload = {"chatId": CHAT_ID, "message": text}
    try:
        resp = requests.post(url, json=payload, timeout=10)
        raw_body = (resp.text or "").strip()
        if not resp.ok:
            return {"ok": False, "detail": f"HTTP {resp.status_code}: {raw_body[:300]}"}
        try:
            data = resp.json()
        except ValueError:
            data = {}
        if isinstance(data, dict) and data.get("error"):
            return {"ok": False, "detail": str(data.get("error"))[:300]}
        message_id = data.get("idMessage") if isinstance(data, dict) else None
        return {"ok": True, "detail": f"idMessage={message_id}" if message_id else "Mensagem aceita pelo provedor"}
    except Exception as exc:
        return {"ok": False, "detail": f"{type(exc).__name__}: {exc}"[:300]}

