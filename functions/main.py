@scheduler_fn.on_schedule(schedule="0 * * * *", timezone="America/Sao_Paulo")
def poll_monitor(event: scheduler_fn.ScheduledEvent) -> None:
    db = firestore.client()
    from datetime import timezone
    now = datetime.now(timezone.utc)

    # D. Garantir que a promoção automática avance mesmo sem ninguém abrir o site.
    try:
        advance_promotion_pipeline(db)
    except Exception as exc:
        print(f"Erro no pipeline automático de promoção: {type(exc).__name__}: {exc}")
    
    # A. Notificar Encerramento (Enquetes que acabaram de expirar)
    expired = db.collection("polls").where("deadline", ">", (now - timedelta(minutes=60)).isoformat()).where("deadline", "<=", now.isoformat()).stream()
    for doc in expired:
        p = doc.to_dict()
        opts = p.get("options", [])
        if not opts: continue
        res = sorted(opts, key=lambda x: x.get('votes', 0), reverse=True)
        winner = res[0].get('label')
        t = p.get("type", "")
        if t in ["repertoire", "repertory"]:
            send_wa_notification_with_logo(build_repertory_result_message(p), db)
        elif t in ["promotion", "tiebreaker"]:
            send_wa_notification_with_logo(build_tiebreaker_result_message(db, p), db)

    # B. Notificar Faltando 24 Horas
    reminder_paused = get_poll_reminder_paused(db)
    if reminder_paused:
        print("Lembretes de enquete (24h/1h) ignorados: pausados pelo admin.")
    else:
        expiring_24h = db.collection("polls").where("deadline", ">", (now + timedelta(hours=23)).isoformat()).where("deadline", "<=", (now + timedelta(hours=24)).isoformat()).stream()
        for doc in expiring_24h:
            p = doc.to_dict() or {}
            if p.get("closed") is True:
                continue
            send_wa_notification_with_logo(build_poll_reminder_message(p, header_title="⏳ *FALTAM 24 HORAS!*"), db)

        # C. Notificar Faltando 1 Hora
        expiring_1h = db.collection("polls").where("deadline", ">", now.isoformat()).where("deadline", "<=", (now + timedelta(hours=1)).isoformat()).stream()
        for doc in expiring_1h:
            p = doc.to_dict() or {}
            if p.get("closed") is True:
                continue
            send_wa_notification_with_logo(build_poll_reminder_message(p, header_title="⚠️ *ÚLTIMA CHAMADA (1 HORA)!*"), db)

