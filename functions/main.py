def lookup_book_recommendation(query):
    import requests
    try:
        response = requests.get(
            "https://www.googleapis.com/books/v1/volumes",
            params={"q": query, "maxResults": 1, "printType": "books"},
            timeout=15,
        )
        response.raise_for_status()
        payload = response.json() or {}
        items = payload.get("items") or []
        if items:
            info = (items[0] or {}).get("volumeInfo") or {}
            image_links = info.get("imageLinks") or {}
            return {
                "ok": True,
                "title": info.get("title") or query,
                "thumbUrl": normalize_image_url(image_links.get("thumbnail") or image_links.get("smallThumbnail") or ""),
                "sourceUrl": info.get("infoLink") or build_google_search_url(f"{query} livro"),
                "sourceLabel": "Google Books"
            }
    except Exception as exc:
        print(f"Google Books lookup failed for {query}: {type(exc).__name__}: {exc}")

    try:
        response = requests.get(
            "https://openlibrary.org/search.json",
            params={"title": query, "limit": 1, "fields": "key,title,cover_i"},
            timeout=15,
        )
        response.raise_for_status()
        payload = response.json() or {}
        docs = payload.get("docs") or []
        if docs:
            book = docs[0] or {}
            cover_id = book.get("cover_i")
            source_key = book.get("key") or ""
            return {
                "ok": True,
                "title": book.get("title") or query,
                "thumbUrl": f"https://covers.openlibrary.org/b/id/{cover_id}-M.jpg" if cover_id else "",
                "sourceUrl": f"https://openlibrary.org{source_key}" if source_key else build_google_search_url(f"{query} livro"),
                "sourceLabel": "Open Library"
            }
    except Exception as exc:
        print(f"Open Library lookup failed for {query}: {type(exc).__name__}: {exc}")

    return {
        "ok": True,
        "title": query,
        "thumbUrl": "",
        "sourceUrl": build_google_search_url(f"{query} livro"),
        "sourceLabel": "Busca Google"
    }

def lookup_tmdb_recommendation(query, media_type):
    import requests
    tmdb_api_key = get_tmdb_api_key()
    if not tmdb_api_key:
        return {
            "ok": True,
            "title": query,
            "thumbUrl": "",
            "sourceUrl": build_google_search_url(f"{query} {media_type}"),
            "sourceLabel": "Busca Google",
            "pendingConfig": True
        }

    endpoint = "tv" if media_type == "series" else "movie"
    response = requests.get(
        f"https://api.themoviedb.org/3/search/{endpoint}",
        params={
            "api_key": tmdb_api_key,
            "language": "pt-BR",
            "query": query,
            "include_adult": "false",
        },
        timeout=15,
    )
    response.raise_for_status()
    payload = response.json() or {}
    results = payload.get("results") or []
    if not results:
        return {
            "ok": True,
            "title": query,
            "thumbUrl": "",
            "sourceUrl": build_google_search_url(f"{query} {media_type}"),
            "sourceLabel": "TMDb"
        }
    item = results[0] or {}
    title = item.get("title") or item.get("name") or query
    poster = item.get("poster_path") or ""
    source_path = f"/movie/{item.get('id')}" if endpoint == "movie" else f"/tv/{item.get('id')}"
    return {
        "ok": True,
        "title": title,
        "thumbUrl": f"https://image.tmdb.org/t/p/w342{poster}" if poster else "",
        "sourceUrl": f"https://www.themoviedb.org{source_path}",
        "sourceLabel": "TMDb"
    }

def build_cifra_candidates(song, artist):
    song_slug = slugify_text(song)
    artist_slug = slugify_text(artist)
    base_song_url = f"https://www.cifraclub.com.br/{artist_slug}/{song_slug}/" if artist_slug and song_slug else ""
    candidates = []
    if base_song_url:
        candidates.append({"label": "Cifra Club principal", "url": base_song_url})
        candidates.append({"label": "Cifra Club simplificada", "url": f"{base_song_url}simplificada.html"})
    if artist_slug:
        candidates.append({"label": "Página do artista no Cifra Club", "url": f"https://www.cifraclub.com.br/{artist_slug}/"})
    search_term = quote_plus(f"{song} {artist} cifra")
    candidates.append({"label": "Busca Google por cifra", "url": f"https://www.google.com/search?q={search_term}"})
    return candidates

