def get_tmdb_api_key():
    if TMDB_API_KEY:
        return TMDB_API_KEY

    now = datetime.utcnow()
    cached_at = TMDB_KEY_CACHE.get("loaded_at")
    if cached_at and TMDB_KEY_CACHE.get("value") is not None and (now - cached_at).total_seconds() < 300:
        return TMDB_KEY_CACHE.get("value") or ""

    try:
        db = firestore.client()
        snap = db.collection("config").document("api_keys").get()
        value = ""
        if snap.exists:
            data = snap.to_dict() or {}
            value = str(data.get("tmdbApiKey") or "").strip()
        TMDB_KEY_CACHE["value"] = value
        TMDB_KEY_CACHE["loaded_at"] = now
        return value
    except Exception:
        TMDB_KEY_CACHE["value"] = ""
        TMDB_KEY_CACHE["loaded_at"] = now
        return ""

